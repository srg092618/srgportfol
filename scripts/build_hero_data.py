"""Rebuild site/assets/hero-data.js from a disease-forecasting (epicast) run.

Usage:
    python scripts/build_hero_data.py path/to/disease-forecasting/outputs

History comes from the horizon-1 rows of backtest_forecasts.csv.gz (the observed value y for
each year); the forecast comes from forecasts.csv, gradient-boosting model.
"""
import json
import sys
from pathlib import Path

import pandas as pd

COUNTRIES = {"ZAF": "South Africa", "MOZ": "Mozambique", "NGA": "Nigeria", "UGA": "Uganda", "KEN": "Kenya"}
QUANTILES = ["q0.025", "q0.1", "q0.25", "q0.5", "q0.75", "q0.9", "q0.975"]
TARGET, MODEL = "hiv_new_infections", "gbm"


def main(outputs: Path) -> None:
    back = pd.read_csv(outputs / "backtest_forecasts.csv.gz", low_memory=False)
    fc = pd.read_csv(outputs / "forecasts.csv", low_memory=False)
    back = back[(back.target == TARGET) & (back.horizon == 1)].copy()
    back["period"] = back.period.astype(int)
    hist = back.groupby(["location", "period"]).y.first()
    data = {}
    for code, name in COUNTRIES.items():
        rows = fc[(fc.target == TARGET) & (fc.model == MODEL) & (fc.location == code)].sort_values("horizon")
        data[code] = {
            "name": name,
            "hist": [[int(p), int(v)] for p, v in hist.loc[code].items()],
            "fc": [[int(r.period)] + [int(round(r[q])) for q in QUANTILES] for _, r in rows.iterrows()],
        }
    out = Path(__file__).resolve().parents[1] / "site" / "assets" / "hero-data.js"
    out.write_text(
        "/* New HIV infections: UNAIDS estimates (history) and the epicast gradient-boosting forecast\n"
        "   (quantiles 2.5, 10, 25, 50, 75, 90, 97.5%). Generated by scripts/build_hero_data.py. */\n"
        "window.HERO_DATA=" + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
